// The second C program the lab runs: examples/cores/cores.c, line for line (a
// test checks the two match). Edit the .c file, then copy its lines here.

export const CORES_C: readonly string[] = [
  "/*",
  " * cores.c: a million marks, added up on several cores at once.",
  " *",
  " * main() fills an array with a million marks, then asks how many threads to",
  " * use. Each thread adds up its own slice of the array, on a core of its own:",
  " * every thread has its own registers and its own stack, while the array, the",
  " * code and the rest of the process's memory are shared by all of them. main()",
  " * waits for each thread, adds up their results and prints the average.",
  " *",
  " *   make && ./cores",
  " *",
  " * The Yanix desktop lab traces this program down to the scheduler and the",
  " * CPU's cores; README.md shows how to watch it for real with strace and gdb.",
  " */",
  "#define _GNU_SOURCE /* for sched_getcpu() */",
  "#include <pthread.h>",
  "#include <sched.h>",
  "#include <stdio.h>",
  "#include <stdlib.h>",
  "",
  "#define MARKS 1000000",
  "#define MAX_THREADS 4",
  "",
  "struct slice {",
  "\tconst int *marks; /* the whole array: every thread shares it */",
  "\tsize_t first;     /* where this thread's part starts */",
  "\tsize_t count;     /* how many marks it adds up */",
  "\tlong sum;         /* the thread's result */",
  "\tint cpu;          /* the CPU the thread finished on */",
  "};",
  "",
  "/* Each new thread starts here, with a stack of its own. */",
  "static void *add_up(void *arg)",
  "{",
  "\tstruct slice *slice = arg; /* points into main()'s stack */",
  "\tlong sum = 0;              /* on this thread's stack */",
  "",
  "\tfor (size_t i = slice->first; i < slice->first + slice->count; i++)",
  "\t\tsum += slice->marks[i];",
  "\tslice->sum = sum;",
  "\tslice->cpu = sched_getcpu();",
  "\treturn NULL;",
  "}",
  "",
  "int main(void)",
  "{",
  "\t/* 4 MB: too big for the heap's usual space, so malloc() maps it on its own */",
  "\tint *marks = malloc(MARKS * sizeof *marks);",
  "\tif (!marks)",
  "\t\treturn 1;",
  "\tfor (size_t i = 0; i < MARKS; i++)",
  "\t\tmarks[i] = i % 101;",
  "",
  "\tchar line[16];",
  "\tfor (;;) {",
  "\t\tprintf(\"How many threads (1 to %d, 0 to stop)? \", MAX_THREADS);",
  "\t\tif (!fgets(line, sizeof line, stdin))",
  "\t\t\tbreak;",
  "\t\tint threads;",
  "\t\tif (sscanf(line, \"%d\", &threads) != 1 || threads < 0 || threads > MAX_THREADS)",
  "\t\t\tcontinue;",
  "\t\tif (threads == 0)",
  "\t\t\tbreak;",
  "",
  "\t\tpthread_t ids[MAX_THREADS];",
  "\t\tstruct slice slices[MAX_THREADS]; /* main()'s stack, shared with the threads */",
  "\t\tsize_t per = MARKS / threads;",
  "",
  "\t\tfor (int t = 0; t < threads; t++) {",
  "\t\t\tslices[t] = (struct slice){",
  "\t\t\t\t.marks = marks,",
  "\t\t\t\t.first = t * per,",
  "\t\t\t\t.count = t == threads - 1 ? MARKS - t * per : per,",
  "\t\t\t};",
  "\t\t\tif (pthread_create(&ids[t], NULL, add_up, &slices[t]) != 0)",
  "\t\t\t\treturn 1;",
  "\t\t}",
  "",
  "\t\tlong total = 0;",
  "\t\tfor (int t = 0; t < threads; t++) {",
  "\t\t\tpthread_join(ids[t], NULL); /* sleeps until thread t has finished */",
  "\t\t\ttotal += slices[t].sum;",
  "\t\t\tprintf(\"thread %d: marks %zu to %zu add up to %ld (finished on CPU %d)\\n\", t + 1,",
  "\t\t\t       slices[t].first, slices[t].first + slices[t].count - 1, slices[t].sum,",
  "\t\t\t       slices[t].cpu);",
  "\t\t}",
  "\t\tprintf(\"average of %d marks: %.5f\\n\", MARKS, (double)total / MARKS);",
  "\t}",
  "\tfree(marks);",
  "\treturn 0;",
  "}",
];
